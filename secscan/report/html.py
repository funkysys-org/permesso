"""Self-contained HTML report (inline CSS, print-friendly)."""
from __future__ import annotations

import html
import json

SEV_COLORS = {
    "CRITICAL": "#a4080e", "HIGH": "#d13b10", "MEDIUM": "#c78a03",
    "LOW": "#3a7a2a", "INFO": "#5b6470",
}

_CSS = """
:root{--ink:#1c2430;--muted:#5b6470;--line:#dfe3ea;--bg:#fbfbf9}
*{box-sizing:border-box}
body{font:15px/1.55 -apple-system,'Segoe UI',Roboto,Helvetica,Arial,sans-serif;
color:var(--ink);background:#fff;margin:0}
.wrap{max-width:880px;margin:0 auto;padding:40px 28px}
h1{font-size:26px;margin:0 0 4px} h2{font-size:18px;margin:34px 0 10px;
border-bottom:2px solid var(--line);padding-bottom:6px}
.muted{color:var(--muted)}
.meta{display:grid;grid-template-columns:1fr 1fr;gap:4px 24px;margin:18px 0;
font-size:13.5px}
.meta div{border-bottom:1px solid var(--line);padding:5px 0}
.meta b{font-weight:600}
.chips{display:flex;gap:8px;flex-wrap:wrap;margin:14px 0 4px}
.chip{color:#fff;font-weight:700;font-size:12.5px;padding:4px 10px;border-radius:20px}
.summary{background:var(--bg);border:1px solid var(--line);border-radius:8px;
padding:14px 16px;margin:18px 0}
.notice{background:#fdf6ec;border:1px solid #ead9bd;border-radius:8px;
padding:10px 14px;margin:12px 0;font-size:13.5px}
.card{border:1px solid var(--line);border-left:5px solid var(--muted);
border-radius:8px;padding:14px 16px;margin:12px 0}
.card .head{display:flex;justify-content:space-between;gap:12px;align-items:baseline}
.card h3{font-size:15.5px;margin:0}
.badge{color:#fff;font-size:11px;font-weight:800;letter-spacing:.6px;
padding:2px 8px;border-radius:4px;white-space:nowrap}
.card .src{font-size:12px;color:var(--muted);margin:4px 0 8px}
pre{background:#f4f5f7;border:1px solid var(--line);border-radius:6px;
padding:8px 10px;font-size:12.5px;overflow-x:auto;white-space:pre-wrap;
word-break:break-word;margin:6px 0}
.remediation{font-size:14px;margin:6px 0 0}
.refs{font-size:12px;margin-top:6px}
footer{margin-top:40px;border-top:1px solid var(--line);padding-top:14px;
font-size:12px;color:var(--muted)}
@media print{.wrap{max-width:none;padding:0}}
"""


def _chip(label: str, count: int) -> str:
    return (f'<span class="chip" style="background:{SEV_COLORS[label]}">'
            f'{label} {count}</span>')


def _card(f: dict) -> str:
    sev = f["severity"]
    color = SEV_COLORS.get(sev, "#5b6470")
    refs = ""
    if f.get("references"):
        links = " ".join(
            f'<a href="{html.escape(r)}">{html.escape(r)}</a>'
            for r in f["references"][:3]
        )
        refs = f'<div class="refs">Refs: {links}</div>'
    evidence = ""
    if f.get("evidence"):
        evidence = f"<pre>{html.escape(str(f['evidence']))}</pre>"
    meta = ""
    if f.get("metadata"):
        meta = (f'<div class="src">meta: '
                f'{html.escape(json.dumps(f["metadata"])[:160])}</div>')
    return f"""
<div class="card" style="border-left-color:{color}">
  <div class="head"><h3>{html.escape(f['title'])}</h3>
  <span class="badge" style="background:{color}">{sev}</span></div>
  <div class="src">{html.escape(f['source'])} · {html.escape(f['target'])}
   · {html.escape(f.get('category',''))} · {html.escape(f.get('id',''))}</div>
  {evidence}{meta}
  <p class="remediation"><b>Fix:</b> {html.escape(f.get('remediation') or '')}</p>
  {refs}
</div>"""


def render(result: dict) -> str:
    counts = result.get("counts", {})
    chips = "".join(_chip(s, counts.get(s, 0)) for s in
                    ("CRITICAL", "HIGH", "MEDIUM", "LOW", "INFO"))
    authz = result.get("authorization", {})
    skipped = result.get("skipped", [])
    notice = ""
    if skipped:
        items = "".join(
            f"<li><b>{html.escape(s['adapter'])}</b>: {html.escape(s['reason'])}</li>"
            for s in skipped
        )
        notice = (f'<div class="notice"><b>Checks skipped</b> (tools not '
                  f'available on this machine): <ul>{items}</ul></div>')
    errors = result.get("errors", [])
    err_notice = ""
    if errors:
        items = "".join(
            f"<li><b>{html.escape(e['adapter'])}</b>: "
            f"{html.escape(e['error'])}</li>" for e in errors
        )
        err_notice = (f'<div class="notice"><b>Adapter errors</b>: '
                      f'<ul>{items}</ul></div>')
    cards = "".join(_card(f) for f in result.get("findings", [])) or \
        "<p class='muted'>No findings from the enabled checks.</p>"
    return f"""<!doctype html>
<html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>secscan report — {html.escape(result.get('host',''))}</title>
<style>{_CSS}</style></head>
<body><div class="wrap">
<h1>Security scan report</h1>
<div class="muted">generated by secscan v{html.escape(str(result.get('version','?')))}</div>
<div class="chips">{chips}</div>
<div class="summary">{html.escape(result.get('summary',''))}</div>
<h2>Scope &amp; authorization</h2>
<div class="meta">
  <div><b>Target</b> {html.escape(result.get('host',''))}</div>
  <div><b>Ports</b> {html.escape(', '.join(map(str, result.get('ports', []))))}</div>
  <div><b>Authorized for</b> {html.escape(str(authz.get('owner','?')))}</div>
  <div><b>Scope</b> {html.escape(str(authz.get('scope','?')))}</div>
  <div><b>Issued</b> {html.escape(str(authz.get('issued_at','?')))}</div>
  <div><b>Expires</b> {html.escape(str(authz.get('expires_at','?')))}</div>
  <div><b>Scan started</b> {html.escape(str(result.get('started_at','?')))}</div>
  <div><b>Scan finished</b> {html.escape(str(result.get('finished_at','?')))}</div>
</div>
{notice}{err_notice}
<h2>Findings ({len(result.get('findings', []))})</h2>
{cards}
<footer>
Every finding above was verified against the authorized target only. Reports
are backed by a signed, expiring authorization record. secscan v0 · scan only
what you are authorized to test.
</footer>
</div></body></html>"""
